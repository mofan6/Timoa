"""Generate the twelve Slint palettes and theme-aware in-page logo assets."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = json.loads((root/'tools/theme-palettes.json').read_text(encoding='utf-8'))
fields = source['fields'] + ['accent-line', 'selection', 'selection-hover']
out = ['// Generated by tools/generate-themes.py from theme-palettes.json.',
       'import { Palette } from "std-widgets.slint";', '', 'export struct ThemePalette {']
out += [f'    {field}: color,' for field in fields]
out += ['}', '', 'export global Theme {', '    in-out property<bool> dark: true;',
        '    in-out property<int> variant: 0;',
        '    changed dark => { Palette.color-scheme = self.dark ? ColorScheme.dark : ColorScheme.light; }',
        '    private property<int> selected: min(5, max(0, self.variant));']
for mode in ['dark', 'light']:
    out.append(f'    private property<[ThemePalette]> {mode}-palettes: [')
    assert len(source[mode]) == 6
    for index, row in enumerate(source[mode]):
        assert len(row) == len(source['fields'])
        values = dict(zip(source['fields'], (color.lower() for color in row)))
        values.update({'accent-line': ('b68a2b55' if mode == 'light' and index == 0 else values['accent'] + ('50' if mode == 'dark' else '55')),
                       'selection': values['accent'] + ('1e' if mode == 'dark' else '22'),
                       'selection-hover': values['accent'] + ('32' if mode == 'dark' else '38')})
        out.append('        { ' + ', '.join(f'{key}: #{value}' for key, value in values.items()) + ' },')
    out.append('    ];')
out.append('    private property<ThemePalette> colors: self.dark ? self.dark-palettes[self.selected] : self.light-palettes[self.selected];')
out += [f'    out property<color> {field}: self.colors.{field};' for field in fields]
out += ['    public pure function swatch(index: int) -> color {',
        '        return self.dark ? self.dark-palettes[min(5, max(0, index))].accent : self.light-palettes[min(5, max(0, index))].accent;',
        '    }', '}']
(root/'ui/theme.slint').write_text('\n'.join(out)+'\n', encoding='utf-8')

directory = root/'assets/themes'
directory.mkdir(exist_ok=True)
for mode in ['dark', 'light']:
    base = (root/'assets'/('logo.svg' if mode == 'dark' else 'logo-light.svg')).read_text(encoding='utf-8')
    for index, row in enumerate(source[mode][1:], start=1):
        values = dict(zip(source['fields'], row))
        icon = base
        replacements = {'F3D17D': values['accent-hover'], 'D6A335': values['accent'], 'E3B341': values['accent'],
                        'F5E8C7': values['text'], '302B20': values['elevated'], '11110F': values['bg'],
                        'CAA13F': values['accent-hover'], 'A87C22': values['accent'], 'BD912D': values['accent'], '50483A': values['text']}
        for old, new in replacements.items(): icon = icon.replace('#'+old, '#'+new)
        (directory/f'{source["names"][index]}-{mode}.svg').write_text(icon, encoding='utf-8')
print('Generated 6 themes × 2 modes and 10 in-page logo variants.')
